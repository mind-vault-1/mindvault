import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const bindingsPath = resolve(root, "packages/registry-client/src/generated/index.ts");
const rustPath = resolve(root, "contract/contracts/vault-registry/src/lib.rs");
const outputPath = resolve(root, "docs/contract-method-event-reference.md");
const checkOnly = process.argv.includes("--check");

function parseMethods() {
  const source = readFileSync(bindingsPath, "utf8");
  const start = source.indexOf("export interface Client {");
  if (start < 0) throw new Error(`Client interface not found in ${bindingsPath}`);
  const end = source.indexOf("\n}", start);
  if (end < 0) throw new Error(`Client interface is not closed in ${bindingsPath}`);

  const methods = [];
  let doc = [];
  for (const line of source.slice(start, end).split(/\r?\n/)) {
    const trimmed = line.trim();
    if (trimmed.startsWith("/**")) {
      doc = [];
      continue;
    }
    if (trimmed.startsWith("*/")) continue;
    if (trimmed.startsWith("*")) {
      const text = trimmed.replace(/^\*\s?/, "").trim();
      if (text && !text.startsWith("Construct and simulate")) doc.push(text);
      continue;
    }
    const match = trimmed.match(/^([a-z][a-z0-9_]*): \((.*)\) => Promise<(.+)>$/);
    if (match) {
      methods.push({
        name: match[1],
        args: match[2],
        returns: match[3],
        description: doc.join(" ").replace(/\s+/g, " ").trim(),
      });
      doc = [];
      continue;
    }
    if (trimmed) doc = [];
  }
  if (methods.length === 0) throw new Error(`No methods parsed from ${bindingsPath}`);
  return methods;
}

function parseEvents() {
  const source = readFileSync(rustPath, "utf8");
  const marker = "pub const EVENT_SCHEMA: &[(&str, &str)] = &[";
  const start = source.indexOf(marker);
  if (start < 0) throw new Error(`EVENT_SCHEMA not found in ${rustPath}`);
  const end = source.indexOf("\n];", start);
  if (end < 0) throw new Error(`EVENT_SCHEMA is not closed in ${rustPath}`);

  const block = source.slice(start, end);
  const pattern = /\(\s*"([^"]+)"\s*,\s*"((?:[^"\\]|\\.)*)"\s*\)/gs;
  const events = [...block.matchAll(pattern)].map((match) => ({
    topic: match[1],
    payload: match[2],
  }));
  if (events.length === 0) throw new Error(`No events parsed from ${rustPath}`);
  return events;
}

function cell(value) {
  return String(value).replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
}

function summary(description) {
  const text = cell(description);
  if (!text) return "—";
  const firstSentence = text.match(/^.+?[.!?](?=\s|$)/)?.[0] ?? text;
  const chosen = firstSentence.length > 200 ? `${firstSentence.slice(0, 199)}…` : firstSentence;
  return chosen;
}

function render(methods, events) {
  const exampleMethod = methods.find((method) => method.name === "register") ?? methods[0];
  const exampleEvent = events.find((event) => event.topic === exampleMethod.name) ?? events[0];

  return `# Contract Method & Event Reference

<!-- Generated by scripts/generate-contract-reference.mjs — do not edit by hand. -->
<!-- Run \`pnpm contract:reference\` to regenerate; CI runs \`pnpm contract:reference:check\`. -->

This page publishes the vault-registry contract surface in one place. Method
signatures are read directly from the checked-in generated bindings at
[\`packages/registry-client/src/generated/index.ts\`](../packages/registry-client/src/generated/index.ts);
event topics and payload shapes are read from \`EVENT_SCHEMA\` in
[\`contract/contracts/vault-registry/src/lib.rs\`](../contract/contracts/vault-registry/src/lib.rs),
the canonical list enforced by the contract tests. The generated Soroban spec
carries method signatures but not event topics, so the two inputs are
deliberately separate.

**${methods.length} methods** and **${events.length} event topics** as of last generation.

## Methods

Every method of the generated \`Client\` interface is listed below. Arguments
and return types are the TypeScript types produced by \`pnpm contract:bindings\`;
\`options\` is the standard method-options bag. The summary is the first sentence
of the binding's doc comment — read the generated file for the full contract.

${methods
  .map(
    (method) =>
      `### \`${cell(method.name)}\`\n\n- **Arguments:** \`${cell(method.args)}\`\n- **Returns:** \`${cell(method.returns)}\`\n- **Summary:** ${summary(method.description)}`,
  )
  .join("\n\n")}

## Events

Event topics are short symbols published as the first segment of the contract
event key; the payload column describes the second segment. See the
[\`contract/README.md\` Events table](../contract/README.md#events) for the
lifecycle conditions that emit each topic.

| Topic | Payload |
| --- | --- |
${events.map((event) => `| \`${cell(event.topic)}\` | \`${cell(event.payload)}\` |`).join("\n")}

## Concrete example

The \`${cell(exampleMethod.name)}\` method is advertised as:

\`\`\`ts
${cell(exampleMethod.name)}: (${cell(exampleMethod.args)}, options?: MethodOptions) => Promise<${cell(exampleMethod.returns)}>
\`\`\`

A successful call emits the \`${cell(exampleEvent.topic)}\` event with payload
\`${cell(exampleEvent.payload)}\`. Indexers should key on the topic, not on the
description, because topics are part of the public ABI.

## Keeping this page fresh

Regenerate the bindings whenever the contract ABI changes, then regenerate
this page:

\`\`\`bash
pnpm contract:bindings
pnpm contract:reference
pnpm contract:reference:check
\`\`\`

The check fails when the committed page differs from the generated one, so a
method or event change cannot ship with stale documentation. No TypeScript
bindings are edited by hand.

## Related docs

- [\`docs/registry-client-bindings.md\`](./registry-client-bindings.md) — how bindings are generated and verified
- [\`docs/contract-upgrade-rehearsal-testnet.md\`](./contract-upgrade-rehearsal-testnet.md) — rehearse a WASM deploy on testnet
- [\`docs/contract-upgrade-checklist.md\`](./contract-upgrade-checklist.md) — release preflight
- [\`contract/README.md\`](../contract/README.md) — hand-maintained contract reference
`;
}

const output = await format(render(parseMethods(), parseEvents()), {
  ...((await resolveConfig(outputPath)) ?? {}),
  filepath: outputPath,
});

if (checkOnly) {
  let current;
  try {
    current = readFileSync(outputPath, "utf8");
  } catch {
    console.error(`${outputPath} does not exist. Run \`pnpm contract:reference\`.`);
    process.exit(1);
  }
  if (current !== output) {
    console.error(`${outputPath} is stale. Run \`pnpm contract:reference\`.`);
    process.exit(1);
  }
  console.log(`${outputPath} is current`);
} else {
  writeFileSync(outputPath, output);
  console.log(`Wrote ${outputPath}`);
}
